package com.kodewala.phonepay9;

public class PhonePeLiterals {
public static void main(String[] args) {
	 int transactionId = 1001;          // Integer literal
     double amount = 1500.50;           // Floating-point literal
     char currencySymbol = '₹';         // Character literal
     boolean paymentSuccessful = true;  // Boolean literal
     String status = "SUCCESS";         // String literal
     String reference = null;           // Null literal

     System.out.println(transactionId);
     System.out.println(amount);
     System.out.println(currencySymbol);
     System.out.println(paymentSuccessful);
     System.out.println(status);
     System.out.println(reference);
}
}
